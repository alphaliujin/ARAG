#!/bin/bash

# =============================================================================
# 敏感信息识别系统 - 一键停止脚本
# =============================================================================
# 用法: ./stop.sh
#
# 停止所有相关服务与后台进程:
#   - 后端 FastAPI (端口 8000) + 残留的 uvicorn/python 进程
#   - 前端 React (端口 3000) + 残留的 react-scripts/node 进程
#   - 清理 .backend.pid / .frontend.pid
#   - 回收僵尸进程
#
# 实际清理逻辑由 start.sh 的 stop_services 统一维护,
# 本脚本仅作转发, 确保停止规则单点真相。
# =============================================================================

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
exec "$SCRIPT_DIR/start.sh" stop
